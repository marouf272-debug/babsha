// Build-time generator for the offline service worker (plan 2.2 offline, D-94). The Vite build
// passes in the built file names; the worker precaches them so the game starts and plays with
// no connection after the first visit. Plain strings only: this runs in Node at build time.

import { createHash } from 'node:crypto';

// The page itself plus every built file, minus source maps.
export function precacheList(bundleFiles: string[]): string[] {
  return ['./', 'index.html', ...bundleFiles.filter((f) => !f.endsWith('.map') && f !== 'index.html' && f !== 'sw.js')];
}

export function serviceWorkerSource(files: string[]): string {
  const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
  return `// Generated by the build (src/build/sw.ts). Do not edit.
const CACHE = ${JSON.stringify(`babsha-${version}`)};
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('babsha-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Pages: network first, so a new release shows up when online; the cached page when offline.
// Built files have content hashes in their names, so the cached copy is always right.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('index.html', { ignoreSearch: true, ignoreVary: true })));
    return;
  }
  event.respondWith(caches.match(request, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(request)));
});
`;
}
